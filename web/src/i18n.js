export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => store.get('mtb-lang') || 'en')
  useEffect(() => {
    store.set('mtb-lang', lang)
    document.documentElement.lang = lang
  }, [lang])
  const t = (key) => STR[lang][key] ?? STR.en[key] ?? key
  return React.createElement(Ctx.Provider, { value: { lang, t, setLang } }, children)
}

export const useI18n = () => useContext(Ctx)
